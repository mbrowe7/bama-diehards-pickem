-- Category-level historical records: for completed seasons, breaks the
-- single season_final_standings W-L down into the categories the league
-- actually tracks (regular season vs bowl, bonus picks, and each individual
-- preseason/postseason award pick), recomputed from the corrected per-week
-- Record/BONUS Record data in the source spreadsheet (the spreadsheet's own
-- "Standings" tab, which season_final_standings mirrors, predates that
-- correction and is left as-is).
--
-- 'overall' and 'regular_season_bonus'/'overall_bonus' are stored
-- explicitly rather than derived, since 'overall' = regular_season + bowl
-- and 'overall_bonus' = regular_season_bonus + bowl's own bonus record,
-- and recomputing that client-side per render isn't worth the duplication
-- this avoids.

create table public.season_category_records (
  id uuid primary key default gen_random_uuid(),
  season_id uuid not null references public.seasons(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  category text not null check (category in (
    'overall', 'regular_season', 'bowl', 'overall_bonus', 'regular_season_bonus',
    'conf_champs', 'playoff_picks', 'national_champion', 'heisman_finalists', 'heisman_winner'
  )),
  wins int not null,
  losses int not null,
  ties int not null default 0,
  unique (season_id, player_id, category)
);

alter table public.season_category_records enable row level security;

create policy "season_category_records_select" on public.season_category_records
  for select to authenticated using (true);

grant select on public.season_category_records to authenticated;

